import 'dart:convert';

/// One note of a scale: what to play (MIDI number, 12-TET name) and where, in first position (string, finger, low/high placement).
/// The target pitch is not here: the grader applies the A4 reference and the tuning system (ADR 0011).
class ScaleNote {
  const ScaleNote({required this.midi, required this.name, required this.string, required this.finger, this.placement});

  final int midi;
  final String name;

  /// 'G', 'D', 'A' or 'E'.
  final String string;

  /// 0 open, 1 to 4.
  final int finger;

  /// 'low' or 'high' where the finger has two first-position places; null otherwise.
  final String? placement;

  factory ScaleNote.fromJson(Map<String, dynamic> j) => ScaleNote(
        midi: j['midi'] as int,
        name: j['name'] as String,
        string: j['string'] as String,
        finger: j['finger'] as int,
        placement: j['placement'] as String?,
      );
}

/// A scale as played: the ascending notes, then the descending notes, the top tonic once.
class ScaleDef {
  const ScaleDef({
    required this.id,
    required this.title,
    required this.key,
    required this.type,
    required this.octaves,
    required this.position,
    required this.ascendingCount,
    required this.notes,
  });

  final String id;
  final String title;

  /// e.g. 'G major', 'A minor'.
  final String key;

  /// 'major', 'natural_minor', 'harmonic_minor' or 'melodic_minor'.
  final String type;
  final int octaves;
  final int position;

  /// How many of [notes] are the ascending half (including the top tonic).
  final int ascendingCount;
  final List<ScaleNote> notes;

  factory ScaleDef.fromJson(Map<String, dynamic> j) => ScaleDef(
        id: j['id'] as String,
        title: j['title'] as String,
        key: j['key'] as String,
        type: j['type'] as String,
        octaves: j['octaves'] as int,
        position: j['position'] as int,
        ascendingCount: j['ascending_count'] as int,
        notes: [for (final n in j['notes'] as List) ScaleNote.fromJson(n as Map<String, dynamic>)],
      );
}

/// The scale definitions shipped with the app (assets/scales/beginner.json, generated by tools/scales/gen_scales.py).
class ScaleLibrary {
  ScaleLibrary(this.scales);

  static const supportedFormat = 1;
  final List<ScaleDef> scales;

  ScaleDef? byId(String id) {
    for (final s in scales) {
      if (s.id == id) return s;
    }
    return null;
  }

  factory ScaleLibrary.fromJsonString(String text) {
    final j = jsonDecode(text) as Map<String, dynamic>;
    if (j['format'] != supportedFormat) throw FormatException('unsupported scale data format ${j['format']}');
    return ScaleLibrary([for (final s in j['scales'] as List) ScaleDef.fromJson(s as Map<String, dynamic>)]);
  }
}
